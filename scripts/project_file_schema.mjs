import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';

const feature = 'lib/features/experiments';
const stampPath = `${feature}/domain/project_file_version.dart`;
const contractFiles = [
  `${feature}/api/project_snapshot.dart`,
  `${feature}/api/test_design.dart`,
  `${feature}/domain/project_file_codec.dart`,
  `${feature}/domain/range_value_parser.dart`,
  `${feature}/domain/sample_size_catalog.dart`,
];

function fingerprint() {
  const hash = createHash('sha256');
  for (const path of contractFiles) {
    const source = readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
    hash.update(path).update('\0').update(source).update('\0');
  }
  const policy = readFileSync('lib/shared/foundation/behavior_policy.dart', 'utf8');
  for (const name of ['maxProjectTitleLength', 'maxProjectFileBytes']) {
    const declaration = policy.match(new RegExp(`\\b${name}\\s*=\\s*([^;]+);`));
    if (!declaration) throw new Error(`Missing project file policy ${name}.`);
    hash.update(declaration[1]).update('\0');
  }
  return hash.digest('hex');
}

function parseStamp(source) {
  const version = Number(source.match(/projectFileSchemaVersion = (\d+);/)?.[1]);
  const digest = source.match(/Contract SHA-256: ([a-f0-9]{64})/)?.[1];
  if (!Number.isSafeInteger(version) || version < 1 || !digest) {
    throw new Error('The project file version stamp is invalid.');
  }
  return { version, digest };
}

function readBaseStamp(ref) {
  const commit = execFileSync('git', ['rev-parse', '--verify', `${ref}^{commit}`], {
    encoding: 'utf8',
  }).trim();
  const path = execFileSync('git', ['ls-tree', '--name-only', commit, '--', stampPath], {
    encoding: 'utf8',
  }).trim();
  if (!path) return null;
  return parseStamp(execFileSync('git', ['show', `${commit}:${stampPath}`], {
    encoding: 'utf8',
  }));
}

function main() {
  const { values: { update, base } } = parseArgs({
    options: { update: { type: 'boolean' }, base: { type: 'string' } },
  });
  const digest = fingerprint();
  const current = existsSync(stampPath)
    ? parseStamp(readFileSync(stampPath, 'utf8'))
    : null;
  const baseline = base ? readBaseStamp(base) : null;
  const minimum = baseline
    ? baseline.version + (digest === baseline.digest ? 0 : 1)
    : 1;
  if (update) {
    const next = current
      ? current.version + (current.digest === digest ? 0 : 1)
      : 1;
    const version = Math.max(minimum, next);
    writeFileSync(stampPath, `// Generated by task project-schema:update.\n// Contract SHA-256: ${digest}\n\n/// Current version of the portable project JSON file.\nconst int projectFileSchemaVersion = ${version};\n`);
    console.log(`Project file schema version ${version}.`);
    return;
  }
  if (current?.digest !== digest || current.version < minimum) {
    const baseArgument = base ? ` BASE=${base}` : '';
    throw new Error(`Project file contract changed. Run task project-schema:update${baseArgument} and commit the version stamp.`);
  }
  console.log(`Project file schema version ${current.version} verified.`);
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
