// Read existing Terraform-managed registrations; never create apps from this script.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync, unlinkSync } from 'node:fs';
import { dirname } from 'node:path';

const firebaseConfig = JSON.parse(readFileSync('firebase.json', 'utf8'));
const platforms = firebaseConfig.flutter.platforms;
platforms.android = {};
platforms.ios = {};
platforms.macos = {};

function write(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
}

function sdk(platform, appId, project) {
  const response = JSON.parse(execFileSync('npx', [
    '-y', 'firebase-tools@latest', 'apps:sdkconfig', platform, appId,
    '--project', project, '--json',
  ], { encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 }));
  if (response.status !== 'success') throw new Error(`Cannot fetch ${platform} config`);
  return response.result.fileContents;
}

for (const environment of ['dev', 'prod']) {
  const outputs = JSON.parse(execFileSync('terraform', [
    `-chdir=infra/environments/${environment}`, 'output', '-json',
  ], { encoding: 'utf8' }));
  const project = outputs.project_id.value;
  const bundleId = 'com.bramwell.bramwellsPrecisionTestKit' + (environment === 'dev' ? '.dev' : '');
  const androidId = outputs.android_app_id.value;
  const appleId = outputs.apple_app_ids.value[bundleId];
  if (!appleId) throw new Error(`Missing Terraform Apple registration for ${bundleId}`);

  const androidPath = `android/app/src/${environment}/google-services.json`;
  const androidContents = sdk('ANDROID', androidId, project);
  write(androidPath, androidContents);
  const android = JSON.parse(androidContents);
  const client = android.client.find((entry) => entry.client_info.mobilesdk_app_id === androidId);
  const packageName = 'com.bramwell.bramwells_precision_test_kit' + (environment === 'dev' ? '.dev' : '');
  if (!client || client.client_info.android_client_info.package_name !== packageName || android.project_info.project_id !== project) {
    throw new Error(`Wrong Android SDK configuration for ${environment}`);
  }
  const appleContents = sdk('IOS', appleId, project);
  for (const platform of ['ios', 'macos']) {
    const path = `${platform}/Firebase/${environment}/GoogleService-Info.plist`;
    write(path, appleContents);
    for (const mode of ['Debug', 'Profile', 'Release']) {
      platforms[platform][`${mode}-${environment}`] = {
        projectId: project, appId: appleId, fileOutput: path, uploadDebugSymbols: false,
      };
    }
  }
  const apple = JSON.parse(execFileSync('plutil', [
    '-convert', 'json', '-o', '-', `ios/Firebase/${environment}/GoogleService-Info.plist`,
  ], { encoding: 'utf8' }));
  if (apple.PROJECT_ID !== project || apple.BUNDLE_ID !== bundleId) throw new Error(`Wrong Apple configuration for ${environment}`);
  platforms.android[environment] = { projectId: project, appId: androidId, fileOutput: androidPath };

  const dartPath = `lib/firebase/firebase_options_${environment}.dart`;
  const oldDart = readFileSync(dartPath, 'utf8');
  const web = oldDart.match(/  static const FirebaseOptions web = FirebaseOptions\([\s\S]*?\n  \);/)[0];
  const windows = oldDart.match(/  static const FirebaseOptions windows = FirebaseOptions\([\s\S]*?\n  \);/)?.[0];
  function options(name, key, appId, applePlatform = false) {
    return `  static const FirebaseOptions ${name} = FirebaseOptions(\n` +
      `    apiKey: ${JSON.stringify(key)},\n    appId: ${JSON.stringify(appId)},\n` +
      `    messagingSenderId: ${JSON.stringify(String(android.project_info.project_number))},\n` +
      `    projectId: ${JSON.stringify(project)},\n` +
      (applePlatform ? `    iosBundleId: ${JSON.stringify(bundleId)},\n` : '') + '  );';
  }
  write(dartPath, `// Generated by scripts/sync_firebase_native.mjs from Firebase CLI SDK config.\n` +
    `import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;\n` +
    `import 'package:flutter/foundation.dart' show defaultTargetPlatform, kIsWeb, TargetPlatform;\n\n` +
    `class DefaultFirebaseOptions {\n  static FirebaseOptions get currentPlatform {\n    if (kIsWeb) return web;\n` +
    `    return switch (defaultTargetPlatform) {\n      TargetPlatform.android => android,\n      TargetPlatform.iOS => ios,\n      TargetPlatform.macOS => macos,\n` +
    (windows ? '      TargetPlatform.windows => windows,\n' : '') +
    `      _ => throw UnsupportedError('Firebase is not configured for this platform.'),\n    };\n  }\n\n` +
    [web, options('android', client.api_key[0].current_key, androidId), options('ios', apple.API_KEY, appleId, true), options('macos', apple.API_KEY, appleId, true), windows].filter(Boolean).join('\n\n') + '\n}\n');
  platforms.dart[dartPath] = {
    projectId: project,
    configurations: { ...platforms.dart[dartPath].configurations, android: androidId, ios: appleId, macos: appleId },
  };
  console.log(`Synchronized ${environment} Android/iOS/macOS configuration for ${project}.`);
}

writeFileSync('firebase.json', JSON.stringify(firebaseConfig, null, 2) + '\n');
for (const oldPath of ['android/app/google-services.json', 'ios/Runner/GoogleService-Info.plist', 'macos/Runner/GoogleService-Info.plist']) {
  if (existsSync(oldPath)) unlinkSync(oldPath);
}
